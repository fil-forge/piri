// Command gen writes eth_client_gen.go: a method on EthClient for every method
// of Curio's ethchain.EthClient, each forwarding the call and recording its
// outcome. Run it through go generate in the chainrpc package whenever Curio's
// interface changes; the compile-time check in eth_client.go fails until then.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"go/types"
	"log"
	"os"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

const (
	ifacePkg  = "github.com/filecoin-project/curio/lib/ethchain"
	ifaceName = "EthClient"
	output    = "eth_client_gen.go"
)

func main() {
	pkgs, err := packages.Load(&packages.Config{Mode: packages.NeedName | packages.NeedTypes}, ifacePkg)
	if err != nil {
		log.Fatalf("loading %s: %v", ifacePkg, err)
	}
	if len(pkgs) != 1 || pkgs[0].Types == nil {
		log.Fatalf("loading %s: no type information", ifacePkg)
	}
	obj := pkgs[0].Types.Scope().Lookup(ifaceName)
	if obj == nil {
		log.Fatalf("%s.%s not found", ifacePkg, ifaceName)
	}
	iface, ok := obj.Type().Underlying().(*types.Interface)
	if !ok {
		log.Fatalf("%s.%s is not an interface", ifacePkg, ifaceName)
	}

	imports := newImportSet()
	imports.add("context", "context")
	var methods bytes.Buffer
	for i := 0; i < iface.NumMethods(); i++ {
		m := iface.Method(i)
		writeMethod(&methods, m.Name(), m.Type().(*types.Signature), imports.qualify)
	}

	var src bytes.Buffer
	src.WriteString("// Code generated by go run ./internal/gen; DO NOT EDIT.\n\n")
	src.WriteString("package chainrpc\n\n")
	src.WriteString(imports.block())
	src.Write(methods.Bytes())

	formatted, err := format.Source(src.Bytes())
	if err != nil {
		log.Fatalf("formatting generated code: %v\n%s", err, src.Bytes())
	}
	if err := os.WriteFile(output, formatted, 0o644); err != nil {
		log.Fatalf("writing %s: %v", output, err)
	}
}

// writeMethod writes one forwarding method. A method that returns an error
// records the call; one that does not (Close) only forwards.
func writeMethod(w *bytes.Buffer, name string, sig *types.Signature, qualify types.Qualifier) {
	params, args, ctxName := describeParams(sig, qualify)
	results := sig.Results()
	returnsErr := results.Len() > 0 && isError(results.At(results.Len()-1).Type())

	var resultDecls []string
	for i := 0; i < results.Len(); i++ {
		resultName := fmt.Sprintf("r%d", i)
		if returnsErr && i == results.Len()-1 {
			resultName = "err"
		}
		resultDecls = append(resultDecls, resultName+" "+types.TypeString(results.At(i).Type(), qualify))
	}

	call := fmt.Sprintf("c.next.%s(%s)", name, strings.Join(args, ", "))
	fmt.Fprintf(w, "func (c *EthClient) %s(%s)", name, strings.Join(params, ", "))
	if len(resultDecls) > 0 {
		fmt.Fprintf(w, " (%s)", strings.Join(resultDecls, ", "))
	}
	w.WriteString(" {\n")
	if returnsErr {
		if ctxName == "" {
			ctxName = "context.Background()"
		}
		fmt.Fprintf(w, "\tdefer func() { c.metrics.recordCall(%s, ClientEth, %q, err) }()\n", ctxName, name)
	}
	if results.Len() > 0 {
		fmt.Fprintf(w, "\treturn %s\n", call)
	} else {
		fmt.Fprintf(w, "\t%s\n", call)
	}
	w.WriteString("}\n\n")
}

// describeParams names the parameters ctx for a context.Context and p<n>
// otherwise, and returns the declarations, the call arguments, and the name of
// the context parameter ("" when there is none).
func describeParams(sig *types.Signature, qualify types.Qualifier) (decls, args []string, ctxName string) {
	params := sig.Params()
	for i := 0; i < params.Len(); i++ {
		t := params.At(i).Type()
		name := fmt.Sprintf("p%d", i)
		if isContext(t) && ctxName == "" {
			name = "ctx"
			ctxName = name
		}
		typeStr := types.TypeString(t, qualify)
		arg := name
		if sig.Variadic() && i == params.Len()-1 {
			typeStr = "..." + strings.TrimPrefix(typeStr, "[]")
			arg += "..."
		}
		decls = append(decls, name+" "+typeStr)
		args = append(args, arg)
	}
	return decls, args, ctxName
}

func isError(t types.Type) bool {
	return types.Identical(t, types.Universe.Lookup("error").Type())
}

func isContext(t types.Type) bool {
	named, ok := t.(*types.Named)
	return ok && named.Obj().Pkg() != nil && named.Obj().Pkg().Path() == "context" && named.Obj().Name() == "Context"
}

// importSet gives each imported package a name unique in the generated file,
// suffixing a number when two packages share one.
type importSet struct {
	nameByPath map[string]string
	pathByName map[string]string
}

func newImportSet() *importSet {
	return &importSet{nameByPath: map[string]string{}, pathByName: map[string]string{}}
}

func (s *importSet) add(path, name string) string {
	if existing, ok := s.nameByPath[path]; ok {
		return existing
	}
	unique := name
	for i := 2; s.pathByName[unique] != ""; i++ {
		unique = fmt.Sprintf("%s%d", name, i)
	}
	s.nameByPath[path] = unique
	s.pathByName[unique] = path
	return unique
}

func (s *importSet) qualify(p *types.Package) string {
	return s.add(p.Path(), p.Name())
}

func (s *importSet) block() string {
	paths := make([]string, 0, len(s.nameByPath))
	for path := range s.nameByPath {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	var b strings.Builder
	b.WriteString("import (\n")
	for _, path := range paths {
		name := s.nameByPath[path]
		if name == path[strings.LastIndex(path, "/")+1:] {
			fmt.Fprintf(&b, "\t%q\n", path)
		} else {
			fmt.Fprintf(&b, "\t%s %q\n", name, path)
		}
	}
	b.WriteString(")\n\n")
	return b.String()
}
